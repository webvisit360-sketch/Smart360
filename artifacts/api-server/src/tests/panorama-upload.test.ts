import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { once } from "node:events";
import { writeFile } from "node:fs/promises";
import express from "express";
import pinoHttp from "pino-http";
import sharp from "sharp";
import { eq } from "drizzle-orm";
import { db, tenantsTable, sectionsTable, categoriesTable, itemsTable, changelogTable } from "@workspace/db";
import router from "../routes/storage";
import { createAdminGateForTests } from "../lib/actorGate";
import { logger } from "../lib/logger";
import { ObjectStorageService, objectStorageClient } from "../lib/objectStorage";

test("DEV multipart panorama upload stores, serves and cleans a large synthetic panorama", async t => {
  assert.ok(process.env.NODE_ENV !== "production" && !process.env.REPLIT_DEPLOYMENT);
  const slug = `panorama-test-${randomUUID()}`;
  const [tenant] = await db.insert(tenantsTable).values({ slug, name: "Synthetic panorama" }).returning();
  const app = express();
  app.use(pinoHttp({ logger }));
  app.use(createAdminGateForTests({ kind: "owner" }));
  app.use(router);
  const server = app.listen(0, "127.0.0.1");
  const listening = once(server, "listening");
  t.after(async () => {
    await new Promise<void>(resolve => server.close(() => resolve()));
    const root = new ObjectStorageService().getPublicObjectSearchPaths()[0].replace(/^\/+/, "");
    const slash = root.indexOf("/");
    const bucket = objectStorageClient.bucket(root.slice(0, slash));
    const prefix = `${root.slice(slash + 1)}/media/${slug}/`;
    const [files] = await bucket.getFiles({ prefix });
    for (const file of files) await file.delete();
    assert.equal((await bucket.getFiles({ prefix }))[0].length, 0);
    await db.delete(changelogTable).where(eq(changelogTable.tenantId, tenant.id));
    await db.delete(tenantsTable).where(eq(tenantsTable.id, tenant.id));
    assert.equal((await db.select().from(tenantsTable).where(eq(tenantsTable.id, tenant.id))).length, 0);
    console.log("Cleanup: test tenants=0, test objects=0; accounts created=0");
  });
  const [section] = await db.insert(sectionsTable).values({ tenantId: tenant.id, key: "explore", title: "Synthetic" }).returning();
  const [category] = await db.insert(categoriesTable).values({ sectionId: section.id, label: "Panorama" }).returning();
  const [item] = await db.insert(itemsTable).values({ categoryId: category.id, title: "Synthetic panorama" }).returning();
  const original = await sharp({ create: { width: 16000, height: 5000, channels: 3, background: "#387aa5" } }).jpeg().toBuffer();
  await listening;
  const address = server.address();
  assert.ok(address && typeof address !== "string");
  const base = `http://127.0.0.1:${address.port}`;
  const form = new FormData();
  form.append("isPanorama", "true");
  form.append("file", new Blob([new Uint8Array(original)], { type: "image/jpeg" }), "synthetic-panorama.jpg");
  const response = await fetch(`${base}/admin/items/${item.id}/media/upload`, { method: "POST", body: form });
  assert.equal(response.status, 201, await response.clone().text());
  const media = await response.json() as { isPanorama: boolean; url: string };
  assert.equal(media.isPanorama, true);
  const served = await fetch(`${base}${media.url.replace(/^\/api/, "")}?w=1400`);
  assert.equal(served.status, 200);
  const servedBytes = Buffer.from(await served.arrayBuffer());
  const dimensions = await sharp(servedBytes).metadata();
  assert.equal(dimensions.width, 8192);
  assert.equal(dimensions.height, 2560);
  await writeFile("/tmp/smart360-panorama-upload-proof.jpg", servedBytes);
  console.log(`Uploaded ${original.length} bytes, 16000x5000; served 8192x2560`);
});
