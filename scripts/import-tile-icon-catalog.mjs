// Deterministic import of the owner's trusted, checked-in SVG catalogue.
// Run from the workspace root. No HTML is accepted from tenants at runtime.
import { readFileSync, writeFileSync } from "node:fs";
const source = "attached_assets/ikone-gumbov-1_1792535751859.html";
const html = readFileSync(source, "utf8");
const decode = (s) => s.replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
const slug = (s) => s.toLowerCase().normalize("NFD").replace(/\p{Diacritic}/gu, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const entries = [...html.matchAll(/<div class="card">([\s\S]*?)(?=<div class="card">|<h2>|<\/body>)/g)].map(([, card]) => {
  const name = card.match(/<div class="name">([^<]+)/)?.[1].trim();
  const svg = decode(card.match(/<pre>([\s\S]*?)<\/pre>/)?.[1] ?? "");
  const keywords = card.match(/<div class="kw"><b>Ključne besede:<\/b>(.*?)<\/div>/)?.[1].split(" / ").map((s) => s.trim()) ?? [];
  if (!name || !svg.startsWith("<svg") || /<script|on\w+=|href=/i.test(svg)) throw new Error("Unexpected catalog card");
  return { id: `catalog:${slug(name)}`, name, keywords, svg };
});
if (entries.length !== 50 || new Set(entries.map((e) => e.id)).size !== entries.length) throw new Error(`Unexpected catalogue: ${entries.length}`);
writeFileSync("lib/category-icons/src/catalog-data.ts", `// Generated by scripts/import-tile-icon-catalog.mjs; do not hand-edit.\nexport const TILE_ICON_CATALOG = ${JSON.stringify(entries, null, 2)} as const;\n`);
console.log(`Imported ${entries.length} exact SVGs`);
